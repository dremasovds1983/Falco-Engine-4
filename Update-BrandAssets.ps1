[CmdletBinding()]
param()
$ErrorActionPreference = 'Stop'
$root = $PSScriptRoot
# Preserve the original Falco artwork and ICO frames byte-for-byte.
foreach ($pair in @(
    @('Res/Brand/Falco.png', 'Res/Editor/Logo.png'),
    @('Res/Brand/Falco.ico', 'Res/Build/icon.ico'),
    @('Res/Brand/InstallerLogo.bmp', 'InstallerAssets/Logo.bmp'),
    @('Res/Brand/InstallerBanner.bmp', 'InstallerAssets/back_picture.bmp')
)) {
    Copy-Item -LiteralPath (Join-Path $root $pair[0]) -Destination (Join-Path $root $pair[1]) -Force
}
$png = [IO.File]::ReadAllBytes((Join-Path $root 'Res/Brand/PlayerLogo.png'))
$lines = [Collections.Generic.List[string]]::new()
$lines.Add('// Generated by Update-BrandAssets.ps1 from Res/Brand/PlayerLogo.png.')
$lines.Add("unsigned char logoRawData[$($png.Length)] = {")
for ($i=0; $i -lt $png.Length; $i+=12) {
    $end = [Math]::Min($i+11,$png.Length-1)
    $lines.Add(([string][char]9) + (($png[$i..$end] | ForEach-Object { '0x{0:X2}' -f $_ }) -join ', ') + ',')
}
$lines.Add('};')
[IO.File]::WriteAllLines((Join-Path $root 'Player/LogoText.c'), $lines, [Text.UTF8Encoding]::new($false))
Write-Host 'Original Falco assets restored; no engine or installer compilation performed.'
